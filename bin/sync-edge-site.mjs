#!/usr/bin/env node
// Projects the site identity into the edge runtime. Cloudflare bundles
// functions/ on its own, so those files cannot import src/lib; the values are
// generated into functions/generated/site.ts the way the contact contract is,
// and check-contract-projections keeps the projection fresh.
import fs from 'node:fs';
import { fromRoot } from '../src/lib/site-root.mjs';
import { SITE } from '../src/lib/site-config.mjs';
import { cspReportPath, cspReportUri, siteOrigin } from '../src/lib/edge-expectations.mjs';

const target = fromRoot('functions/generated/site.ts');
const projection = {
  domain: SITE.domain,
  origin: siteOrigin,
  cspReportPath,
  cspReportUri,
};
const output = `// GENERATED by bin/sync-edge-site.mjs from src/lib/site-config.mjs — do not edit.\nexport const SITE = ${JSON.stringify(projection, null, 2)} as const;\n`;

if (process.argv.includes('--check')) {
  if (!fs.existsSync(target) || fs.readFileSync(target, 'utf8') !== output) {
    console.error('functions/generated/site.ts is stale; run npm run sync:edge-site');
    process.exit(1);
  }
  console.log('ok: functions/generated/site.ts derives from src/lib/site-config.mjs');
} else {
  fs.writeFileSync(target, output);
  console.log(`wrote ${target}`);
}
