#!/usr/bin/env node
// Project the site identity into functions/generated/site.ts: Cloudflare bundles
// functions/ separately, so they cannot import src/lib.
import { checkMode } from './lib/args.ts';
import { writeOrCheck } from './lib/projection.ts';
import { fromRoot } from '../src/lib/site-root.ts';
import { SITE } from '../src/lib/site-config.ts';
import { cspReportPath, cspReportUri, siteOrigin } from '../src/lib/edge-expectations.ts';

const check = checkMode('usage: node bin/sync-edge-site.ts [--check]');
const projection = {
  domain: SITE.domain,
  origin: siteOrigin,
  cspReportPath,
  cspReportUri,
};
const output = `// GENERATED by bin/sync-edge-site.ts from src/lib/site-config.ts. Do not edit.\nexport const SITE = ${JSON.stringify(projection, null, 2)} as const;\n`;

writeOrCheck([{ file: fromRoot('functions/generated/site.ts'), content: output }], { check, hint: 'npm run sync:edge-site' });
if (check) console.log('ok       functions/generated/site.ts derives from src/lib/site-config.ts');
