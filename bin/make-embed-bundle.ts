// Emit the one embeddable stylesheet:
//
//   public/embed/bundle.css  =  base.css (which imports the brand vars), its Inter inlined as base64
//
// Served at https://jseverino.com/embed/bundle.css for the vault theme and Obsidian.
//
//   node bin/make-embed-bundle.ts           # (re)write public/embed/bundle.css
//   node bin/make-embed-bundle.ts --check   # fail if the committed copy is stale

import { buildSync } from 'esbuild';
import { fromRoot, siteRoot } from '../src/lib/site-root.ts';
import { checkMode } from './lib/args.ts';
import { writeOrCheck } from './lib/projection.ts';

const check = checkMode('usage: node bin/make-embed-bundle.ts [--check]');

// base.css with its @imports inlined in cascade order and every value left as written: no
// minify and no target, so nesting and longhands such as animation-timeline pass through.
// The site's own /assets/ URLs stay URLs, and the font tokens.css declares becomes a data URL.
// absWorkingDir keeps the per-file path comments independent of where the script runs.
const { outputFiles } = buildSync({
  entryPoints: [fromRoot('src/styles/base.css')],
  bundle: true,
  write: false,
  external: ['/assets/*'],
  loader: { '.woff2': 'dataurl' },
  absWorkingDir: siteRoot,
});
const baseCss = outputFiles[0]?.text ?? '';

const bundle = [
  '/* GENERATED by bin/make-embed-bundle.ts. Do not edit.',
  ' * The one embeddable stylesheet: brand vars + base.css + inlined Inter.',
  ' * Regenerate: mise run make:embed · drift-gated by mise run checks:contracts. */',
  baseCss,
].join('\n');

writeOrCheck([{ file: fromRoot('public/embed/bundle.css'), content: bundle }], { check });
if (check) console.log('ok       public/embed/bundle.css matches its sources');
