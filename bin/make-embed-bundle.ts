#!/usr/bin/env node
// Emit the one embeddable stylesheet.
//
// The "load BOTH" contract (src/lib/web-styles.ts) says an embedder needs
// base.css + the brand vars + a resolvable Inter TOGETHER. previewStyles()
// shares the assembly, but each embedder supplies baseCss/fontUrl its own way.
// This emits the whole contract as one artifact:
//
//   public/embed/bundle.css  =  base.css (which imports the brand vars) + @font-face (base64 Inter)
//
// Deployed at https://jseverino.com/embed/bundle.css. The vault theme and the
// Obsidian cockpit load that one URL (or this file), so none can miss the
// brand vars.
//
//   node bin/make-embed-bundle.ts           # (re)write public/embed/bundle.css
//   node bin/make-embed-bundle.ts --check   # fail if the committed copy is stale
import fs from 'node:fs';
import { checkMode } from './lib/args.ts';
import { readCssEntry } from './lib/css-entry.ts';
import { writeOrCheck } from './lib/projection.ts';
import { fromRoot } from '../src/lib/site-root.ts';
import { interFontFace } from '../src/lib/web-styles.ts';

const check = checkMode('usage: node bin/make-embed-bundle.ts [--check]');
const baseCss = readCssEntry(fromRoot('src/styles/base.css'));
const font = fs.readFileSync(fromRoot('public/assets/fonts/inter/inter-variable-latin.woff2'));

const bundle = [
  '/* GENERATED by bin/make-embed-bundle.ts. Do not edit.',
  ' * The one embeddable stylesheet: brand vars + base.css + inlined Inter.',
  ' * Regenerate: npm run -s make:embed · drift-gated by the contract-projections audit. */',
  baseCss,
  interFontFace(`data:font/woff2;base64,${font.toString('base64')}`),
  '',
].join('\n');

writeOrCheck([{ file: fromRoot('public/embed/bundle.css'), content: bundle }], { check, hint: 'npm run -s make:embed' });
if (check) console.log('ok       public/embed/bundle.css matches its sources');
