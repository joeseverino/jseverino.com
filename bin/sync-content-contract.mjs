#!/usr/bin/env node
import fs from 'node:fs';
import path from 'node:path';
import { siteRoot } from '../src/lib/site-root.mjs';
import {
  contentContract,
  contentContractFingerprint,
} from '../src/lib/content-contract.mjs';

const root = siteRoot;
const mcpRoot = process.env.SEVERINO_VAULT_MCP_ROOT
  ? path.resolve(process.env.SEVERINO_VAULT_MCP_ROOT)
  : path.resolve(root, '../../Assets/severino-vault-mcp');
const checkMcpProjection = Boolean(process.env.SEVERINO_VAULT_MCP_ROOT);
const mcpTarget = path.join(
  mcpRoot,
  'src/severino_vault_mcp/contracts/site_content.v1.json',
);
const schemaTarget = path.join(root, 'src/generated/content-schema.ts');
const projection = `${JSON.stringify({
  source: 'jseverino.com/contracts/content.v1.json',
  fingerprint: contentContractFingerprint(),
  contract: contentContract,
}, null, 2)}\n`;
const check = process.argv.includes('--check');

function zodExpression(spec) {
  const base = {
    boolean: 'z.boolean()',
    date: 'z.coerce.date()',
    integer: 'z.number().int()',
    'string[]': 'z.array(z.string())',
    string: 'z.string()',
  }[spec.type];
  if (!base) throw new Error(`unsupported content field type: ${spec.type}`);
  if ('default' in spec) return `${base}.default(${JSON.stringify(spec.default)})`;
  return spec.required ? base : `${base}.optional()`;
}

const schemaSource = [
  '// GENERATED by bin/sync-content-contract.mjs — do not edit.',
  `// Contract fingerprint: ${contentContractFingerprint()}`,
  "import { z } from 'astro:content';",
  '',
  ...Object.entries(contentContract.collections).flatMap(([collection, definition]) => [
    `export const ${collection}Schema = z.object({`,
    ...Object.entries(definition.fields).map(([name, spec]) => `  ${name}: ${zodExpression(spec)},`),
    '});',
    '',
  ]),
].join('\n');

if (check) {
  if (!fs.existsSync(schemaTarget) || fs.readFileSync(schemaTarget, 'utf8') !== schemaSource) {
    console.error(`content schema projection is stale: ${schemaTarget}`);
    console.error('run: npm run sync:contract');
    process.exit(1);
  }
  if (checkMcpProjection && fs.existsSync(mcpRoot)) {
    const current = fs.existsSync(mcpTarget) ? fs.readFileSync(mcpTarget, 'utf8') : '';
    if (current !== projection) {
      console.error(`content contract projection is stale: ${mcpTarget}`);
      console.error('run: npm run sync:contract');
      process.exit(1);
    }
  }
  console.log(`ok: content contract projection ${contentContractFingerprint().slice(0, 12)}`);
} else {
  fs.mkdirSync(path.dirname(schemaTarget), { recursive: true });
  fs.writeFileSync(schemaTarget, schemaSource);
  console.log(`wrote ${schemaTarget}`);
  if (fs.existsSync(mcpRoot)) {
    fs.mkdirSync(path.dirname(mcpTarget), { recursive: true });
    fs.writeFileSync(mcpTarget, projection);
    console.log(`wrote ${mcpTarget}`);
  }
}
