#!/usr/bin/env node
import fs from 'node:fs';
import path from 'node:path';
import { siteRoot } from '../src/lib/site-root.mjs';

const root = siteRoot;
const contract = JSON.parse(fs.readFileSync(path.join(root, 'contracts/contact.v1.json'), 'utf8'));
const target = path.join(root, 'db/contact-openapi.json');
const moduleTarget = path.join(root, 'functions/generated/contact-contract.ts');
const response = (description, ref) => ({
  description,
  content: { 'application/json': { schema: { $ref: ref } } },
});
const document = {
  openapi: '3.0.3',
  info: {
    title: 'jseverino.com Contact API',
    version: '1.0.0',
    description: 'Schema for the public contact form endpoint.',
  },
  servers: [{ url: 'https://jseverino.com' }],
  paths: {
    '/api/contact': {
      post: {
        summary: 'Submit a contact form message',
        operationId: 'submitContactMessage',
        requestBody: {
          required: true,
          content: { 'application/json': { schema: { $ref: '#/components/schemas/ContactSubmission' } } },
        },
        responses: {
          200: response('Submission accepted or honeypot submission ignored.', '#/components/schemas/ContactSuccess'),
          400: response('Malformed or invalid submission.', '#/components/schemas/ContactError'),
          413: response('Request body is too large.', '#/components/schemas/ContactError'),
          415: response('Request content type is not JSON.', '#/components/schemas/ContactError'),
          429: response('Too many submissions from the same IP address.', '#/components/schemas/ContactError'),
          500: response('Submission could not be saved.', '#/components/schemas/ContactError'),
        },
      },
    },
  },
  components: {
    schemas: {
      ContactSubmission: contract.request,
      ContactSuccess: {
        type: 'object', additionalProperties: false, required: ['ok'],
        properties: { ok: { type: 'boolean', enum: [true] } },
      },
      ContactError: {
        type: 'object', additionalProperties: false, required: ['ok', 'error'],
        properties: { ok: { type: 'boolean', enum: [false] }, error: { type: 'string' } },
      },
    },
  },
};
const output = `${JSON.stringify(document, null, 2)}\n`;
const moduleOutput = [
  '// GENERATED by bin/sync-contact-openapi.mjs — do not edit.',
  `export const contactContract = ${JSON.stringify(contract, null, 2)} as const;`,
  '',
].join('\n');
if (process.argv.includes('--check')) {
  if (!fs.existsSync(target) || fs.readFileSync(target, 'utf8') !== output) {
    console.error('db/contact-openapi.json is stale; run npm run sync:contact-openapi');
    process.exit(1);
  }
  if (!fs.existsSync(moduleTarget) || fs.readFileSync(moduleTarget, 'utf8') !== moduleOutput) {
    console.error('functions/generated/contact-contract.ts is stale; run npm run sync:contact-openapi');
    process.exit(1);
  }
  console.log('ok: contact OpenAPI and runtime module derive from contracts/contact.v1.json');
} else {
  fs.writeFileSync(target, output);
  fs.mkdirSync(path.dirname(moduleTarget), { recursive: true });
  fs.writeFileSync(moduleTarget, moduleOutput);
  console.log(`wrote ${target}`);
  console.log(`wrote ${moduleTarget}`);
}
